# ─── HTML Template ───────────────────────────────────────────────────────────

def _text_to_html(report_text: str) -> str:
    """Convert a plain-text report to a styled HTML email."""
    # Escape HTML
    import html
    escaped = html.escape(report_text)

    # Apply color highlighting
    lines = escaped.split("\n")
    styled_lines = []
    for line in lines:
        if "CRITICAL" in line or "🔴" in line:
            styled_lines.append(f'<span style="color:#ef4444;font-weight:bold;">{line}</span>')
        elif "WARNING" in line or "🟡" in line:
            styled_lines.append(f'<span style="color:#eab308;font-weight:bold;">{line}</span>')
        elif "SUGGESTION" in line or "🔵" in line:
            styled_lines.append(f'<span style="color:#3b82f6;">{line}</span>')
        elif line.startswith("=") or line.startswith("─") or line.startswith("═"):
            styled_lines.append(f'<span style="color:#6b7280;">{line}</span>')
        elif "✅" in line or "HEALTHY" in line:
            styled_lines.append(f'<span style="color:#22c55e;font-weight:bold;">{line}</span>')
        elif "❌" in line or "ACTION REQUIRED" in line:
            styled_lines.append(f'<span style="color:#ef4444;font-weight:bold;">{line}</span>')
        else:
            styled_lines.append(line)

    report_html = "<br>".join(styled_lines)
    today = datetime.now().strftime("%A, %B %d, %Y")

    return f"""<!DOCTYPE html>
<html>
<head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
</head>
<body style="margin:0;padding:0;background-color:#0f172a;font-family:'Segoe UI',Roboto,'Helvetica Neue',Arial,sans-serif;">
    <div style="max-width:640px;margin:0 auto;padding:24px;">
        <!-- Header -->
        <div style="background:linear-gradient(135deg,#1e293b 0%,#334155 100%);border-radius:12px 12px 0 0;padding:32px 24px;text-align:center;">
            <h1 style="margin:0;color:#f8fafc;font-size:24px;">🐰 Local Rabbit</h1>
            <p style="margin:8px 0 0;color:#94a3b8;font-size:14px;">Daily Audit Report — {today}</p>
        </div>

        <!-- Body -->
        <div style="background:#1e293b;padding:24px;border-radius:0 0 12px 12px;border:1px solid #334155;border-top:none;">
            <pre style="font-family:'JetBrains Mono','Fira Code','Cascadia Code',monospace;font-size:13px;line-height:1.6;color:#e2e8f0;white-space:pre-wrap;word-wrap:break-word;margin:0;">
{report_html}
            </pre>
        </div>

        <!-- Footer -->
        <div style="text-align:center;padding:16px;color:#64748b;font-size:12px;">
            <p>Generated by Local Rabbit Orchestrator</p>
            <p style="color:#475569;">This is an automated report. Configure in config.json</p>
        </div>
    </div>
</body>
</html>"""


# ─── Email Sending ───────────────────────────────────────────────────────────

def send_email(subject: str, html_body: str, config: dict, attachment_path: str = None) -> bool:
    """Send an HTML email via SMTP.

    Args:
        subject: Email subject line
        html_body: HTML content
        config: Email config dict with smtp_host, smtp_port, smtp_user, from, to, etc.
        attachment_path: Optional file to attach

    Returns:
        True if sent successfully
    """
    smtp_host = config.get("smtp_host", "")
    smtp_port = config.get("smtp_port", 587)
    smtp_user = config.get("smtp_user", "")
    smtp_password = os.environ.get(config.get("smtp_password_env", "SMTP_PASSWORD"), "")
    from_addr = config.get("from", smtp_user)
    to_addrs = config.get("to", [])

    if not smtp_host or not to_addrs:
        logging.warning("Email not configured (missing smtp_host or to addresses)")
        return False

    if not smtp_password:
        logging.warning(f"SMTP password not set (env var: {config.get('smtp_password_env', 'SMTP_PASSWORD')})")
        return False

    msg = MIMEMultipart("alternative")
    msg["Subject"] = subject
    msg["From"] = from_addr
    msg["To"] = ", ".join(to_addrs)

    # Attach HTML body
    msg.attach(MIMEText(html_body, "html", "utf-8"))

    # Optional file attachment
    if attachment_path and Path(attachment_path).exists():
        try:
            with open(attachment_path, "rb") as f:
                part = MIMEBase("application", "octet-stream")
                part.set_payload(f.read())
            encoders.encode_base64(part)
            part.add_header(
                "Content-Disposition",
                f'attachment; filename="{Path(attachment_path).name}"',
            )
            msg.attach(part)
        except Exception as e:
            logging.warning(f"Failed to attach file: {e}")

    try:
        with smtplib.SMTP(smtp_host, smtp_port, timeout=30) as server:
            server.ehlo()
            if smtp_port != 25:  # Skip STARTTLS for port 25 (unencrypted)
                server.starttls()
                server.ehlo()
            server.login(smtp_user, smtp_password)
            server.sendmail(from_addr, to_addrs, msg.as_string())
        logging.info(f"📧 Email sent to {', '.join(to_addrs)}")
        return True
    except smtplib.SMTPAuthenticationError:
        logging.error("📧 SMTP authentication failed. Check credentials.")
        return False
    except smtplib.SMTPException as e:
        logging.error(f"📧 SMTP error: {e}")
        return False
    except Exception as e:
        logging.error(f"📧 Email error: {e}")
        return False


def send_daily_digest(report_text: str, config: dict) -> bool:
    """Convert a text report to HTML and send as daily digest email."""
    html = _text_to_html(report_text)
    today = datetime.now().strftime("%Y-%m-%d")
    subject = f"🐰 Local Rabbit — Daily Audit Report ({today})"

    # Also save the JSON report as attachment
    audit_dir = PROJECT_ROOT / "data" / "audit_history"
    latest_audit = None
    if audit_dir.exists():
        audits = sorted(audit_dir.glob("audit-*.json"), reverse=True)
        if audits:
            latest_audit = str(audits[0])

    return send_email(subject, html, config, attachment_path=latest_audit)


def send_critical_alert(file_path: str, issues: list, config: dict) -> bool:
    """Send an immediate alert email for critical issues."""
    if not config.get("on_critical", True):
        return False

    report = f"🚨 CRITICAL ISSUE DETECTED\n\n"
    report += f"File: {file_path}\n"
    report += f"Time: {datetime.now().strftime('%H:%M:%S')}\n\n"
    report += "Issues:\n"
    for issue in issues:
        report += f"  • {issue}\n"

    html = _text_to_html(report)
    subject = f"🚨 Local Rabbit — Critical Issue in {Path(file_path).name}"
    return send_email(subject, html, config)


